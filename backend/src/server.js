import dotenv from 'dotenv'; dotenv.config();
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import { connectDB } from './config/db.js';
import authRoutes from './routes/auth.js';
import memoryRoutes from './routes/memories.js';
import documentRoutes from './routes/documents.js';
import chatRoutes from './routes/chat.js';
import projectRoutes from './routes/projects.js';
import dashboardRoutes from './routes/dashboard.js';

const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL || '*', credentials: true }));
app.use(express.json({ limit: '5mb' }));
app.use(morgan('dev'));
app.get('/', (_,res)=>res.json({name:'Synapse AI API',status:'healthy'}));
app.use('/api/auth', authRoutes);
app.use('/api/memories', memoryRoutes);
app.use('/api/documents', documentRoutes);
app.use('/api/chat', chatRoutes);
app.use('/api/projects', projectRoutes);
app.use('/api/dashboard', dashboardRoutes);
app.use((err,req,res,next)=>res.status(500).json({message:err.message||'Server error'}));
const port = process.env.PORT || 5000;
connectDB().then(()=>app.listen(port,()=>console.log(`API running on ${port}`))).catch(err=>{console.error(err);process.exit(1);});
